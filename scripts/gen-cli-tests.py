#!/usr/bin/env python3
"""Generate exhaustive CLI-flag integration tests for rustfetch.

The binary's own ``--help`` output is the single source of truth: we parse
every documented long flag, pick a harmless representative value for its
argument kind, and emit one Rust integration test per flag.

Usage:
    python3 scripts/gen-cli-tests.py [PATH_TO_BINARY]

Binary resolution order:
    1. the first command-line argument
    2. $CARGO_BIN_EXE_rustfetch
    3. <repo>/target/release/rustfetch

Output:
    <repo>/tests/cli_flags_generated.rs

The generator is deterministic: flags are sorted by name, no timestamps or
machine-specific paths are embedded, so re-running against the same binary
produces byte-identical output.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

HEADER = (
    "AUTO-GENERATED by scripts/gen-cli-tests.py - do not edit by hand; "
    "re-run the generator."
)

# Flags that are documented but must not be exercised automatically because
# they have destructive / persistent side effects. Every flag that is actually
# skipped is recorded in a comment in the generated file.
UNSAFE_FLAGS = {
    "--gen-config": "writes a generated config file to a path on disk",
    "--uninstall": "removes installed files from the system",
}

# A relative name that does not exist. Image/file logo flags accept it and
# silently fall back to no logo; no file is created or modified.
SENTINEL_PATH = "__rustfetch_generated_no_such_file__"

# Flag-specific overrides. These either avoid a destructive value, avoid a
# non-terminating watch loop, or supply an enum spelling the parser accepts.
VALUE_OVERRIDES = {
    "--config": "none",  # no config file I/O at all
    "--format": "json",  # valid enum, exits immediately after printing
    "--logo": "none",
    "--logo-type": "auto",
    "--logo-position": "auto",
    "--logo-cache": "true",
    "--structure": "os",
    "--structure-disabled": "os",
    "--data": "hi",
    "--data-raw": "hi",
    "--logo-color-1": "red",
    "--key-language": "en",
    "--key-type": "string",
    "--temp-unit": "C",
    "--size-binary-prefix": "IEC",
    "--size-max-prefix": "GB",
    "--percent-type": "2",
    "--chafa-canvas-mode": "TRUECOLOR",
    "--chafa-color-space": "RGB",
    "--chafa-dither-mode": "NONE",
    "--ds-force-drm": "false",
    "--duration-space-before-unit": "default",
    "--fraction-trailing-zeros": "default",
    "--freq-space-before-unit": "default",
    "--percent-space-before-unit": "default",
    "--size-space-before-unit": "default",
    "--temp-space-before-unit": "default",
    # A positive value keeps these flags running forever; zero disables the
    # watch loop and lets the process exit normally.
    "--dynamic-interval": "0",
    "--watch": "0",
}

PATH_FLAGS = {
    "--file",
    "--file-raw",
    "--raw",
    "--sixel",
    "--kitty",
    "--kitty-direct",
    "--kitty-icat",
    "--iterm",
    "--chafa",
}

KIND_DEFAULTS = {
    "bool": "true",
    "num": "2",
    "enum": "default",
    "color": "red",
    "str": "x",
    "string": "x",
    "data": "hi",
    "path": SENTINEL_PATH,
    "logo": "none",
    "config": "none",
    "structure": "os",
}

FLAG_RE = re.compile(r"^--([A-Za-z0-9\[\]-]+)")
VALUE_RE = re.compile(r"<\??([A-Za-z][A-Za-z0-9-]*)>")
SHORT_PREFIX_RE = re.compile(r"^-[A-Za-z0-9]+,\s+")
BRACKET_RE = re.compile(r"\[[^\]]*\]")


def resolve_binary(argv: list[str]) -> Path:
    repo_root = Path(__file__).resolve().parent.parent
    candidate = argv[1] if len(argv) > 1 else os.environ.get("CARGO_BIN_EXE_rustfetch")
    if candidate:
        path = Path(candidate)
        if not path.is_absolute():
            path = (Path.cwd() / path).resolve()
    else:
        path = repo_root / "target" / "release" / "rustfetch"
    if not path.is_file():
        raise SystemExit(f"error: binary not found: {path}")
    return path


def help_text(binary: Path) -> str:
    result = subprocess.run(
        [str(binary), "--help"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    text = result.stdout.decode("utf-8", errors="replace")
    text += result.stderr.decode("utf-8", errors="replace")
    if "--" not in text:
        raise SystemExit("error: no long flags found in --help output")
    return text


def parse_help(text: str) -> dict[str, tuple[str | None, bool]]:
    """Return {normalized flag: (value kind or None, optional?)} in help order."""
    flags: dict[str, tuple[str | None, bool]] = {}
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("-") and not line.startswith("--"):
            match = SHORT_PREFIX_RE.match(line)
            if match is None:
                continue
            line = line[match.end() :]
        if not line.startswith("--"):
            continue
        match = FLAG_RE.match(line)
        if match is None:
            continue
        raw_name = match.group(1)
        rest = line[match.end() :].split(":", 1)[0]
        name = BRACKET_RE.sub("1", raw_name)  # --logo-color-[1-9] -> --logo-color-1
        flag = f"--{name}"
        value_match = VALUE_RE.search(rest)
        if value_match is None:
            kind, optional = None, False
        else:
            kind = value_match.group(1)
            optional = rest[value_match.start() + 1] == "?"
        flags.setdefault(flag, (kind, optional))
    return flags


def test_name(flag: str, used: set[str]) -> str:
    base = "flag_" + re.sub(r"[^a-z0-9]+", "_", flag[2:].lower()).strip("_")
    name = base
    suffix = 2
    while name in used:
        name = f"{base}_{suffix}"
        suffix += 1
    used.add(name)
    return name


def values_for(flag: str, kind: str | None) -> list[str]:
    if flag in VALUE_OVERRIDES:
        return [VALUE_OVERRIDES[flag]]
    if flag in PATH_FLAGS:
        return [SENTINEL_PATH]
    if kind is None:
        return []  # bare flag
    if kind == "command":  # --help <?command>: bare avoids a noisy diagnostic
        return []
    if kind in KIND_DEFAULTS:
        return [KIND_DEFAULTS[kind]]
    return ["2"]


def rust_string(value: str) -> str:
    # All values are ASCII and free of quotes/backslashes; this is a guard
    # against emitting malformed Rust if that ever changes.
    if any(char in value for char in ('"', "\\", "\n", "\r", "\t")):
        raise SystemExit(f"error: unsupported value for generated Rust: {value!r}")
    return f'"{value}"'


RUST_PRELUDE = """// {header}
//
// Source of truth: the `--help` output of the rustfetch binary. This file is
// regenerated by `python3 scripts/gen-cli-tests.py <binary>`.
//
// Parsed {parsed} documented long flag(s); skipped {skipped} unsafe flag(s);
// generated {generated} flag test(s) plus one count-consistency test.
//
// Skipped flags (documented but destructive):
{skip_lines}
//
// Each flag test runs `<binary> --pipe -s os <FLAG> [VALUE]` and asserts:
//   * the exit status is success
//   * stderr contains none of: `panicked at`, `SIGSEGV`, `SIGILL`
//   * stdout is valid UTF-8
// Safe, non-persistent values are chosen per flag kind; path-like flags use
// a relative name that does not exist, so nothing is read or written.

const PARSED_FLAG_COUNT: usize = {parsed};
const SKIPPED_FLAG_COUNT: usize = {skipped};
const GENERATED_FLAG_COUNT: usize = {generated};

const SKIPPED_FLAGS: &[(&str, &str)] = &[
{skip_entries}
];

fn rustfetch() -> std::process::Command {{
    // NO_CONFIG keeps auto-loaded user config out of these smoke tests.
    let mut command = std::process::Command::new(env!("CARGO_BIN_EXE_rustfetch"));
    command.env("NO_CONFIG", "1");
    command
}}

fn run_flag(args: &[&str]) {{
    let output = match rustfetch().args(args).output() {{
        Ok(output) => output,
        Err(error) => panic!("failed to spawn rustfetch: {{error}}"),
    }};
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        output.status.success(),
        "rustfetch {{args:?}} exited with {{:?}}; stderr: {{stderr}}",
        output.status
    );
    for marker in ["panicked at", "SIGSEGV", "SIGILL"] {{
        assert!(
            !stderr.contains(marker),
            "rustfetch {{args:?}} printed crash marker {{marker:?}}: {{stderr}}"
        );
    }}
    if let Err(error) = String::from_utf8(output.stdout) {{
        panic!("rustfetch {{args:?}} wrote invalid UTF-8 to stdout: {{error}}");
    }}
}}

// Mirrors the generator's help parser so a stale generated file is detected
// when the binary's `--help` output changes.
fn normalize_pseudo(name: &str) -> String {{
    let mut out = String::new();
    let mut in_bracket = false;
    for ch in name.chars() {{
        if ch == '[' {{
            in_bracket = true;
            out.push('1');
        }} else if ch == ']' {{
            in_bracket = false;
        }} else if !in_bracket {{
            out.push(ch);
        }}
    }}
    out
}}

fn parse_help_flags(help: &str) -> Vec<String> {{
    let mut flags: Vec<String> = Vec::new();
    for line in help.lines() {{
        let mut line = line.trim();
        if line.starts_with('-') && !line.starts_with("--") {{
            let Some(comma) = line.find(',') else {{ continue; }};
            line = line[comma + 1..].trim();
        }}
        if !line.starts_with("--") {{
            continue;
        }}
        let name: String = line[2..]
            .chars()
            .take_while(|ch| ch.is_ascii_alphanumeric() || *ch == '-' || *ch == '[' || *ch == ']')
            .collect();
        if name.is_empty() {{
            continue;
        }}
        let flag = format!("--{{}}", normalize_pseudo(&name));
        if !flags.contains(&flag) {{
            flags.push(flag);
        }}
    }}
    flags
}}
"""


def generate(binary: Path) -> str:
    flags = parse_help(help_text(binary))
    sorted_flags = sorted(flags.items())  # deterministic: alphabetical by flag

    skips = [(flag, UNSAFE_FLAGS[flag]) for flag, _ in sorted_flags if flag in UNSAFE_FLAGS]
    kept = [(flag, kind) for flag, (kind, _) in sorted_flags if flag not in UNSAFE_FLAGS]

    used: set[str] = set()
    tests = []
    for flag, kind in kept:
        name = test_name(flag, used)
        args = ["--pipe", "-s", "os", flag, *values_for(flag, kind)]
        rendered = ", ".join(rust_string(arg) for arg in args)
        tests.append(f"#[test]\nfn {name}() {{\n    run_flag(&[{rendered}]);\n}}\n")

    skip_lines = (
        "\n".join(f"//   {flag}: {reason}" for flag, reason in skips)
        if skips
        else "//   (none)"
    )
    skip_entries = (
        "\n".join(
            f'    ({rust_string(flag)}, {rust_string(reason)}),'
            for flag, reason in skips
        )
        if skips
        else "    // (none)"
    )

    prelude = RUST_PRELUDE.format(
        header=HEADER,
        parsed=len(sorted_flags),
        skipped=len(skips),
        generated=len(kept),
        skip_lines=skip_lines,
        skip_entries=skip_entries,
    )

    count_test = """#[test]
fn generated_count_matches_parsed_flag_count() {
    let output = match rustfetch().arg("--help").output() {
        Ok(output) => output,
        Err(error) => panic!("failed to spawn rustfetch --help: {error}"),
    };
    assert!(output.status.success(), "rustfetch --help failed");
    let help = match String::from_utf8(output.stdout) {
        Ok(help) => help,
        Err(error) => panic!("rustfetch --help wrote invalid UTF-8: {error}"),
    };
    let parsed = parse_help_flags(&help);
    assert_eq!(
        parsed.len(),
        PARSED_FLAG_COUNT,
        "--help changed ({} flags, expected {}); re-run scripts/gen-cli-tests.py",
        parsed.len(),
        PARSED_FLAG_COUNT
    );
    let generated: Vec<&str> = parsed
        .iter()
        .map(String::as_str)
        .filter(|flag| !SKIPPED_FLAGS.iter().any(|(skipped, _)| skipped == flag))
        .collect();
    assert_eq!(generated.len(), GENERATED_FLAG_COUNT);
    assert_eq!(PARSED_FLAG_COUNT, GENERATED_FLAG_COUNT + SKIPPED_FLAG_COUNT);
}
"""

    return prelude + "\n" + "\n".join(tests) + "\n" + count_test


def main() -> None:
    binary = resolve_binary(sys.argv)
    repo_root = Path(__file__).resolve().parent.parent
    output_dir = repo_root / "tests"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "cli_flags_generated.rs"
    content = generate(binary)
    output_path.write_text(content, encoding="utf-8")
    print(
        f"wrote {output_path} ({content.count('#[test]')} tests; "
        f"source: {binary})"
    )


if __name__ == "__main__":
    main()
